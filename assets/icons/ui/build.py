"""Build the offline SVG family from icons.json. Run from any directory; stdlib only."""
import html
import json
import re
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
catalog = json.loads((HERE / 'icons.json').read_text())
icons, aliases = catalog['icons'], catalog['aliases']
attrs = 'xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"'
markup, symbols = {}, []
for name, icon in icons.items():
    assert re.fullmatch(r'[a-z][a-z0-9-]*', name), name
    body = ET.fromstring('<g>' + icon['body'] + '</g>')
    assert len(body) and all(node.tag in {'g', 'path', 'circle', 'rect', 'ellipse', 'line', 'polyline', 'polygon'} for node in body.iter()), name
    markup[name] = f'<svg class="i" {attrs} aria-hidden="true" data-ui-icon="{name}">{icon["body"]}</svg>'
    (HERE / f'{name}.svg').write_text(f'<svg {attrs} role="img" aria-label="{html.escape(icon["label"], quote=True)}">{icon["body"]}</svg>\n')
    symbols.append(f'<symbol id="{name}" viewBox="0 0 24 24">{icon["body"]}</symbol>')
for alias, name in aliases.items():
    assert re.fullmatch(r'[a-z][a-z0-9-]*', alias) and name in icons and alias not in icons, alias
    markup[alias] = markup[name]
    symbols.append(f'<symbol id="{alias}" viewBox="0 0 24 24">{icons[name]["body"]}</symbol>')
(HERE / 'sprite.svg').write_text('<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">' + ''.join(symbols) + '</svg>\n')
(HERE / 'icons.js').write_text('// Generated by build.py from icons.json. Do not edit.\nwindow.MindbatonIcons = ' + json.dumps(markup, ensure_ascii=False, separators=(',', ':')) + ';\n')
with zipfile.ZipFile(HERE / 'mindbaton-ui-icons.zip', 'w', zipfile.ZIP_DEFLATED) as bundle:
    for name in icons:
        bundle.write(HERE / f'{name}.svg', f'{name}.svg')
    for name in ['sprite.svg', 'icons.js', 'icons.json', 'build.py', 'README.md']:
        if (HERE / name).exists():
            bundle.write(HERE / name, name)
print(f'Built {len(icons)} SVG icons, sprite, runtime and ZIP; {len(aliases)} caller aliases.')
